/* Пачка конвертации. status:'sent' — рубли ушли, USDT ещё в пути.
   extra — мелкие сделки, уехавшие тем же переводом: по ним будут свои задачи. */
function scrCnv(d,o,extra){
  const src=[{dealId:d.id,payer:d.client,date:now().slice(0,5),rub:d.incomeAmount||d.amountRub,usdt:null}]
    .concat((extra||[]).map(x=>({dealId:x.id,payer:x.client,date:now().slice(0,5),rub:x.amountRub,usdt:null})));
  if(extra&&extra.length) d.conv=extra.map(x=>x.id);
  const c=seedCnv(Object.assign({broker:'Tradex',requestNo:'48',rate:'81,35',at:now(),walletId:'vitaly',
    sources:src,txs:[]},o));
  const rate=num(c.rate);
  c.sources.forEach(s=>{
    const share=c.rubTotal?(s.rub||0)/c.rubTotal:1;
    if(s.usdt==null&&rate) s.usdt=Math.round(c.sent*share/rate*100)/100;
    /* пока USDT не пришли, фактической суммы нет — её даёт хеш, а не курс */
    if(c.status!=='received') delete s.usdtFact;
  });
  return c;
}

function scrAmt(v){return Number(v).toLocaleString('ru-RU',{minimumFractionDigits:2,maximumFractionDigits:2});}

/* USDT пришли: хеш — это факт, сумма берётся из него */
function scrCnvReceived(d,extra){
  const c=scrCnv(d,{status:'received'},extra);
  const got=c.sources.reduce((s,x)=>s+(x.usdt||0),0);
  c.txs=[{hash:'ed7f9fcd31249fcc0b6a7d2f2a5b18c4e9107ab3c8d5fe2210947bb6cd83ff41',
          net:'TRC20',amount:got,to:'TKkeEVf2zySaWTLyX2qPwvi6kcdHRuPxkJ',toLabel:'Кошелёк Виталия'}];
  c.receivedAt=now();
  c.sources.forEach(s=>{s.usdtFact=s.usdt;});
  d.pay.usdt=got;d.pay.hash=c.txs[0].hash;
  d.payinHashes=[{amount:got,network:'TRC20',hash:c.txs[0].hash}];
  return c;
}

function scrShare(c,x){const s=c.sources.find(y=>y.dealId===x.id);return s?(s.usdtFact!=null?s.usdtFact:s.usdt):0;}
function scrTask(x,kind,o){
  x.postConv=kind;
  x.transfer=Object.assign({},o);
  if(kind==='coins') x.paySrc='coins';
  if(kind==='ipps')  x.paySrc='ipps';
}

